"""Generate a standalone Python driver class for one device.

Input: `protocol_entries` rows for a `device_name`.
Output: a single .py file with a class that wraps `bleak`, exposing a method per
write entry and a property + notification callback per read entry. The user's
encoder/decoder snippets are inlined verbatim — they are the device-specific
truth and we don't try to be clever about them.

Design constraints:
  - Generated code has zero bt-spy import. Drop it into any project.
  - One file. No "framework." Easy to audit.
  - Methods are async and return either None (writes) or the decoded value (reads).
  - Snake_case class name → CamelCase. We sanitize aggressively.
"""

from __future__ import annotations

import keyword
import re
import textwrap
from dataclasses import dataclass
from pathlib import Path

from .. import db


@dataclass
class DriverEntry:
    name: str           # canonical method name (from vocabulary or user)
    handle: int
    char_uuid: str | None
    direction: str
    encoder_py: str | None
    decoder_py: str | None
    structure_json: str | None


def _camel(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def _identifier(name: str) -> str:
    # Strip anything not safe in a Python identifier.
    cleaned = re.sub(r"[^A-Za-z0-9_]", "_", name).strip("_") or "fn"
    if cleaned[0].isdigit():
        cleaned = "f_" + cleaned
    if keyword.iskeyword(cleaned):
        cleaned = cleaned + "_"
    return cleaned


def _indent(body: str, n: int = 8) -> str:
    return textwrap.indent(body.rstrip(), " " * n)


def _load_entries(device_name: str) -> list[DriverEntry]:
    conn = db.init_db()
    rows = db.list_protocol_entries(conn, device_name=device_name)
    if not rows:
        raise ValueError(
            f"No protocol entries for device {device_name!r}. "
            "Save some via the Protocol Dict UI / MCP first."
        )
    return [
        DriverEntry(
            name=r["name"],
            handle=r["handle"],
            char_uuid=r["char_uuid"],
            direction=r["direction"],
            encoder_py=r["encoder_py"],
            decoder_py=r["decoder_py"],
            structure_json=r["structure_json"],
        )
        for r in rows
    ]


HEADER = '''\
"""Auto-generated by bt-spy from protocol_entries for device {device_name!r}.

Do not edit by hand — re-run `bt-spy export-driver {device_name}` to regenerate.
The encoder/decoder snippets here come directly from your protocol entries.
"""

from __future__ import annotations

import asyncio
import logging
from typing import Any, Awaitable, Callable

from bleak import BleakClient, BleakScanner
from bleak.exc import BleakError

log = logging.getLogger(__name__)


class {class_name}:
    """Driver for {device_name}."""

    def __init__(self, address: str) -> None:
        self.address = address
        self._client: BleakClient | None = None
        self._notify_callbacks: dict[str, list[Callable[[Any], Awaitable[None] | None]]] = {{}}

    # ---------- lifecycle ----------

    @classmethod
    async def discover(cls, timeout: float = 10.0) -> list["{class_name}"]:
        """BLE-scan and return a driver per matching device.

        Override `_matches` if you want stricter than name-substring matching.
        """
        out: list[{class_name}] = []
        for dev in await BleakScanner.discover(timeout=timeout):
            if cls._matches(dev):
                out.append(cls(dev.address))
        return out

    @classmethod
    def _matches(cls, dev) -> bool:
        return bool(dev.name and "{device_name}".lower() in dev.name.lower())

    async def connect(self) -> None:
        if self._client and self._client.is_connected:
            return
        self._client = BleakClient(self.address, timeout=15.0)
        await self._client.connect()
        # Re-subscribe to any notify chars whose callbacks survived a reconnect.
        for uuid in list(self._notify_callbacks):
            await self._client.start_notify(uuid, self._make_notify_handler(uuid))

    async def disconnect(self) -> None:
        if self._client:
            try:
                await self._client.disconnect()
            finally:
                self._client = None

    async def __aenter__(self) -> "{class_name}":
        await self.connect()
        return self

    async def __aexit__(self, *exc) -> None:
        await self.disconnect()

    # ---------- helpers ----------

    async def _write(self, char_uuid: str, payload: bytes, *, response: bool = False) -> None:
        if not self._client or not self._client.is_connected:
            await self.connect()
        assert self._client is not None
        await self._client.write_gatt_char(char_uuid, payload, response=response)

    async def _read(self, char_uuid: str) -> bytes:
        if not self._client or not self._client.is_connected:
            await self.connect()
        assert self._client is not None
        return bytes(await self._client.read_gatt_char(char_uuid))

    def on(self, name: str, cb: Callable[[Any], Awaitable[None] | None]) -> None:
        """Register a callback for a notify entry. Call after connect()."""
        uuid = NOTIFY_UUIDS.get(name)
        if not uuid:
            raise ValueError(f"No notify characteristic for {{name!r}}")
        self._notify_callbacks.setdefault(uuid, []).append(cb)

    def _make_notify_handler(self, uuid: str):
        def handler(_sender, data: bytearray) -> None:
            payload = bytes(data)
            decoded = NOTIFY_DECODERS.get(uuid, lambda p: p)(payload)
            for cb in self._notify_callbacks.get(uuid, []):
                result = cb(decoded)
                if asyncio.iscoroutine(result):
                    asyncio.create_task(result)
        return handler

    async def start_notifications(self) -> None:
        """Subscribe to every characteristic the driver knows how to decode."""
        if not self._client or not self._client.is_connected:
            await self.connect()
        for uuid in NOTIFY_UUIDS.values():
            try:
                await self._client.start_notify(uuid, self._make_notify_handler(uuid))
            except BleakError as exc:
                log.warning("start_notify(%s) failed: %s", uuid, exc)

'''


WRITE_METHOD_TEMPLATE = '''\

    async def {method_name}(self, *args, **kwargs) -> None:
        """{docstring}"""
{encoder_block}
        payload = _encode_{method_name}(*args, **kwargs)
        await self._write({char_uuid!r}, payload, response={response})
'''


READ_METHOD_TEMPLATE = '''\

    async def {method_name}(self) -> Any:
        """{docstring}"""
{decoder_block}
        raw = await self._read({char_uuid!r})
        return _decode_{method_name}(raw)
'''


def _encoder_block(method_name: str, snippet: str | None) -> str:
    if snippet:
        return _indent(_rewrite_top_level_fn(snippet, f"_encode_{method_name}"), 8)
    # Fallback: encoder that just hexlifies its single argument
    return _indent(
        f"def _encode_{method_name}(payload_hex: str) -> bytes:\n"
        f"    return bytes.fromhex(payload_hex)",
        8,
    )


def _decoder_block(method_name: str, snippet: str | None) -> str:
    if snippet:
        return _indent(_rewrite_top_level_fn(snippet, f"_decode_{method_name}"), 8)
    return _indent(
        f"def _decode_{method_name}(payload: bytes) -> bytes:\n"
        f"    return payload",
        8,
    )


_FN_DEF_RE = re.compile(r"^(\s*)def\s+([A-Za-z_]\w*)\s*\(", re.M)


def _rewrite_top_level_fn(snippet: str, new_name: str) -> str:
    """Rename the snippet's top-level function (e.g. `def decode(...)`) to `new_name`.

    Users author snippets as `def decode(payload):` / `def encode(**kw):`. We rename
    so multiple snippets can coexist in one file without colliding.
    """
    dedented = textwrap.dedent(snippet)
    return _FN_DEF_RE.sub(lambda m: f"{m.group(1)}def {new_name}(", dedented, count=1)


def generate_driver_code(device_name: str) -> str:
    entries = _load_entries(device_name)
    class_name = _camel(device_name) or "Device"

    notify_uuids: dict[str, str] = {}
    write_methods: list[str] = []
    read_methods: list[str] = []

    for e in entries:
        method_name = _identifier(e.name)
        if e.char_uuid is None:
            # Skip but record — without UUID we can't address the characteristic
            # from a non-bt-spy process. Tell the user.
            note = f"    # NOTE: protocol entry {e.name!r} has no char_uuid — add it via UI / MCP."
            (read_methods if "peripheral->central" in (e.direction or "") else write_methods).append(note)
            continue

        if e.direction == "central->peripheral":
            write_methods.append(WRITE_METHOD_TEMPLATE.format(
                method_name=method_name,
                docstring=f"Write '{e.name}' (handle={e.handle}). Args match your encoder snippet.",
                encoder_block=_encoder_block(method_name, e.encoder_py),
                char_uuid=e.char_uuid,
                response="False",
            ))
        else:
            # peripheral->central → read or notify. We expose both behaviours:
            # `await device.<name>()` does a one-shot read; on('<name>', cb) subscribes.
            read_methods.append(READ_METHOD_TEMPLATE.format(
                method_name=method_name,
                docstring=f"Read '{e.name}' (handle={e.handle}).",
                decoder_block=_decoder_block(method_name, e.decoder_py),
                char_uuid=e.char_uuid,
            ))
            notify_uuids[e.name] = e.char_uuid

    header = HEADER.format(device_name=device_name, class_name=class_name)
    body = "".join(write_methods + read_methods)

    notify_uuid_decl = "NOTIFY_UUIDS = {\n" + "".join(
        f"    {k!r}: {v!r},\n" for k, v in notify_uuids.items()
    ) + "}\n\n"
    notify_decoders_decl = "NOTIFY_DECODERS: dict[str, Any] = {}\n"
    # Wire decoders for each notify by mapping uuid → callable above. We do this
    # at import time using the module's own functions.
    if notify_uuids:
        wires = []
        for name in notify_uuids:
            mname = _identifier(name)
            wires.append(f"NOTIFY_DECODERS[{notify_uuids[name]!r}] = _decode_{mname}")
        wires_block = "\n".join(wires) + "\n"
    else:
        wires_block = ""

    footer = (
        "\n\n"
        + notify_uuid_decl
        + notify_decoders_decl
        + wires_block
        + "\n"
        + f'__all__ = ["{class_name}"]\n'
    )

    return header + body + footer


def write_driver(device_name: str, out: Path) -> Path:
    code = generate_driver_code(device_name)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(code)
    return out
