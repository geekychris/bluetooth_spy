"""Scaffold a Home Assistant custom_component for one device.

Output layout:

    custom_components/<slug>/
    ├── __init__.py        — setup + unload, wires the coordinator
    ├── manifest.json      — domain, version, bluetooth matchers, requirements
    ├── const.py           — DOMAIN, scan interval, the device class name
    ├── config_flow.py     — bluetooth-discovery-driven config flow
    ├── coordinator.py     — DataUpdateCoordinator wrapping the device driver
    ├── driver.py          — the standalone driver (generated by driver.py)
    └── <platform>.py …    — one file per HA platform inferred from protocol_entries

Platforms are inferred from `integrations.vocabulary`:
  - write entries → platform = light / switch / cover / fan / climate / lock
  - read entries  → platform = sensor / binary_sensor / event

Entry names that aren't in the vocabulary land as TODO comments — they still
exist on the driver, they just aren't wired into HA entities.

Notes:
  - We target HA 2024.4+. The bluetooth integration has been stable since 2022.
  - Generated code is meant to *load* in HA and be a good starting point. Real
    devices often need state coalescing logic that's hard to infer from raw
    protocol entries — leave room for handcrafted refinements.
"""

