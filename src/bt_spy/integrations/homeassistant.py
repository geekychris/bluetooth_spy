@dataclass
class ScaffoldHints:
    """Optional hints the user can provide at scaffold time.

    All optional. If absent we make sensible guesses or leave TODOs.
    """
    local_name: str | None = None             # used in manifest bluetooth matcher
    service_uuid: str | None = None
    manufacturer_id: int | None = None
    manufacturer: str = "Unknown"
    model: str | None = None
    sw_version: str = "0.1.0"


def _slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9_]+", "_", name.lower()).strip("_")
    return s or "device"


def scaffold(
    device_name: str,
    out_dir: Path,
    hints: ScaffoldHints | None = None,
) -> list[Path]:
    hints = hints or ScaffoldHints()
    slug = _slug(device_name)
    component_dir = out_dir / slug
    component_dir.mkdir(parents=True, exist_ok=True)

    entries = _entries(device_name)
    writes = [e for e in entries if e["direction"] == "central->peripheral"]
    reads = [e for e in entries if e["direction"] != "central->peripheral"]

    write_buckets = vocab.classify_writes([e["name"] for e in writes])
    read_buckets = vocab.classify_reads([e["name"] for e in reads])

    written: list[Path] = []

    def w(path: Path, content: str) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        written.append(path)

    class_name = driver_mod._camel(device_name)

    w(component_dir / "manifest.json", _manifest(slug, device_name, hints))
    w(component_dir / "const.py", _const(slug, device_name, class_name))
    w(component_dir / "__init__.py", _init_py(write_buckets, read_buckets))
    w(component_dir / "coordinator.py", _coordinator(class_name))
    w(component_dir / "config_flow.py", _config_flow(slug, device_name, class_name, hints))
    w(component_dir / "driver.py", driver_mod.generate_driver_code(device_name))

    # Per-platform entity files
    if "light" in write_buckets:
        w(component_dir / "light.py", _light_py(class_name, write_buckets["light"]))
    if "switch" in write_buckets:
        w(component_dir / "switch.py", _switch_py(class_name, write_buckets["switch"]))
    if "cover" in write_buckets:
        w(component_dir / "cover.py", _cover_py(class_name, write_buckets["cover"]))
    if "fan" in write_buckets:
        w(component_dir / "fan.py", _fan_py(class_name, write_buckets["fan"]))
    if "climate" in write_buckets:
        w(component_dir / "climate.py", _climate_py(class_name, write_buckets["climate"]))
    if "lock" in write_buckets:
        w(component_dir / "lock.py", _lock_py(class_name, write_buckets["lock"]))

    if "sensor" in read_buckets:
        w(component_dir / "sensor.py", _sensor_py(class_name, read_buckets["sensor"]))
    if "binary_sensor" in read_buckets:
        w(component_dir / "binary_sensor.py", _binary_sensor_py(class_name, read_buckets["binary_sensor"]))

    # Hand the user a punchlist of unmapped names
    unknown_writes = write_buckets.get("unknown", [])
    unknown_reads = read_buckets.get("unknown", [])
    if unknown_writes or unknown_reads:
        w(component_dir / "TODO.md", _todo_md(unknown_writes, unknown_reads))

    w(component_dir / "README.md", _readme(slug, device_name, list(write_buckets), list(read_buckets)))
    return written


def _entries(device_name: str) -> list[dict]:
    conn = db.init_db()
    rows = db.list_protocol_entries(conn, device_name=device_name)
    if not rows:
        raise ValueError(f"No protocol entries for {device_name!r}.")
    return rows


# --- file templates -------------------------------------------------------

def _manifest(slug: str, device_name: str, h: ScaffoldHints) -> str:
    matcher: dict = {}
    if h.local_name:
        matcher["local_name"] = h.local_name
    if h.service_uuid:
        matcher["service_uuid"] = h.service_uuid
    if h.manufacturer_id is not None:
        matcher["manufacturer_id"] = h.manufacturer_id
    if not matcher:
        # Lacking hints, match any device whose name contains the device_name slug.
        matcher = {"local_name": f"{device_name}*"}

    manifest = {
        "domain": slug,
        "name": device_name,
        "codeowners": ["@you"],
        "config_flow": True,
        "dependencies": ["bluetooth"],
        "documentation": "https://example.invalid/replace-me",
        "iot_class": "local_polling",
        "requirements": ["bleak>=0.21"],
        "version": h.sw_version,
        "bluetooth": [matcher],
    }
    return json.dumps(manifest, indent=2) + "\n"


def _const(slug: str, device_name: str, class_name: str) -> str:
    return textwrap.dedent(f'''\
        """Constants for the {device_name} integration."""

        DOMAIN = "{slug}"
        MANUFACTURER = "Unknown"
        DEVICE_CLASS_NAME = "{class_name}"

        DEFAULT_SCAN_INTERVAL_SECS = 60
    ''')


def _init_py(write_buckets: dict[str, list[str]], read_buckets: dict[str, list[str]]) -> str:
    platforms = sorted(set(write_buckets) | set(read_buckets) - {"unknown"})
    platforms = [p for p in platforms if p != "unknown"]
    return textwrap.dedent(f'''\
        """Auto-generated by bt-spy. Entry point for the integration."""

        from __future__ import annotations

        import logging

        from homeassistant.config_entries import ConfigEntry
        from homeassistant.const import Platform
        from homeassistant.core import HomeAssistant

        from .const import DOMAIN
        from .coordinator import DeviceCoordinator

        PLATFORMS: list[Platform] = [{", ".join(f"Platform.{p.upper()}" for p in platforms)}]

        _LOGGER = logging.getLogger(__name__)


        async def async_setup_entry(hass: HomeAssistant, entry: ConfigEntry) -> bool:
            address = entry.data["address"]
            coordinator = DeviceCoordinator(hass, address)
            await coordinator.async_config_entry_first_refresh()
            hass.data.setdefault(DOMAIN, {{}})[entry.entry_id] = coordinator
            await hass.config_entries.async_forward_entry_setups(entry, PLATFORMS)
            return True


        async def async_unload_entry(hass: HomeAssistant, entry: ConfigEntry) -> bool:
            ok = await hass.config_entries.async_unload_platforms(entry, PLATFORMS)
            if ok:
                coordinator: DeviceCoordinator = hass.data[DOMAIN].pop(entry.entry_id)
                await coordinator.driver.disconnect()
            return ok
    ''')


def _coordinator(class_name: str) -> str:
    return textwrap.dedent(f'''\
        """DataUpdateCoordinator wrapping the standalone device driver."""

        from __future__ import annotations

        from datetime import timedelta
        import logging

        from homeassistant.core import HomeAssistant
        from homeassistant.helpers.update_coordinator import DataUpdateCoordinator, UpdateFailed

        from .const import DEFAULT_SCAN_INTERVAL_SECS, DOMAIN
        from .driver import {class_name}

        _LOGGER = logging.getLogger(__name__)


        class DeviceCoordinator(DataUpdateCoordinator[dict]):
            def __init__(self, hass: HomeAssistant, address: str) -> None:
                super().__init__(
                    hass, _LOGGER, name=DOMAIN,
                    update_interval=timedelta(seconds=DEFAULT_SCAN_INTERVAL_SECS),
                )
                self.driver = {class_name}(address)

            async def _async_update_data(self) -> dict:
                try:
                    await self.driver.connect()
                    # Poll readable characteristics. Override or extend per-device.
                    snapshot: dict[str, object] = {{}}
                    for attr in dir(self.driver):
                        if attr.startswith("_"):
                            continue
                        # Heuristic: read methods are async no-arg.
                        fn = getattr(self.driver, attr)
                        if not callable(fn):
                            continue
                        # Skip the lifecycle / helper methods.
                        if attr in ("discover", "connect", "disconnect", "on", "start_notifications"):
                            continue
                        try:
                            snapshot[attr] = await fn()
                        except TypeError:
                            # Method takes args → it's a write, skip.
                            continue
                        except Exception as exc:
                            _LOGGER.debug("read %s failed: %s", attr, exc)
                    return snapshot
                except Exception as exc:
                    raise UpdateFailed(str(exc)) from exc
    ''')


def _config_flow(slug: str, device_name: str, class_name: str, h: ScaffoldHints) -> str:
    return textwrap.dedent(f'''\
        """Bluetooth-discovery-driven config flow."""

        from __future__ import annotations

        import logging

        import voluptuous as vol
        from homeassistant import config_entries
        from homeassistant.components.bluetooth import (
            BluetoothServiceInfoBleak,
            async_discovered_service_info,
        )

        from .const import DOMAIN

        _LOGGER = logging.getLogger(__name__)


        class ConfigFlow(config_entries.ConfigFlow, domain=DOMAIN):
            VERSION = 1

            def __init__(self) -> None:
                self._discovered: dict[str, BluetoothServiceInfoBleak] = {{}}

            async def async_step_bluetooth(self, info: BluetoothServiceInfoBleak):
                await self.async_set_unique_id(info.address)
                self._abort_if_unique_id_configured()
                return self.async_create_entry(title=info.name or "{device_name}", data={{"address": info.address}})

            async def async_step_user(self, user_input: dict | None = None):
                if user_input is not None:
                    addr = user_input["address"]
                    await self.async_set_unique_id(addr)
                    self._abort_if_unique_id_configured()
                    info = self._discovered[addr]
                    return self.async_create_entry(title=info.name or "{device_name}", data={{"address": addr}})

                for info in async_discovered_service_info(self.hass):
                    if info.name and "{(h.local_name or device_name).lower()}" in info.name.lower():
                        self._discovered[info.address] = info
                if not self._discovered:
                    return self.async_abort(reason="no_devices_found")
                schema = vol.Schema({{vol.Required("address"): vol.In(
                    {{addr: f"{{info.name}} ({{addr}})" for addr, info in self._discovered.items()}}
                )}})
                return self.async_show_form(step_id="user", data_schema=schema)
    ''')


