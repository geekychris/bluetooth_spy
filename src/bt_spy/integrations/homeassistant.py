def _todo_md(unknown_writes: list[str], unknown_reads: list[str]) -> str:
    lines = ["# Unmapped protocol entries", ""]
    if unknown_writes:
        lines.append("## Writes (no HA entity generated):")
        lines += [f"- `{n}`" for n in unknown_writes] + [""]
    if unknown_reads:
        lines.append("## Reads (no HA entity generated):")
        lines += [f"- `{n}`" for n in unknown_reads] + [""]
    lines.append(
        "Either rename these to entries in `bt_spy.integrations.vocabulary` and re-scaffold, "
        "or add the appropriate entity classes by hand. The driver still exposes them as methods."
    )
    return "\n".join(lines) + "\n"


